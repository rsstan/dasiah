#!/usr/bin/env bash
# End-to-end stack: Compose profile `full` as project heatmap-e2e, with its own volumes, its own
# generated secrets (.e2e/.env, git-ignored) and only the web page published (E2E_WEB_PORT,
# default 8088). It never touches the development stack or the root .env.
#   scripts/e2e.sh up     build images, start, wait until healthy
#   scripts/e2e.sh down   stop and remove containers and volumes
#   scripts/e2e.sh logs   logs of every container
set -euo pipefail
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
env_file="$root/.e2e/.env"

generate_env() {
  mkdir -p "$root/.e2e"
  local key
  key="$(openssl genpkey -algorithm ed25519 2>/dev/null | awk 'BEGIN{ORS="\\n"} {print}')"
  {
    echo "# Generated by scripts/e2e.sh for the end-to-end stack only."
    echo "POSTGRES_DB=heatmap"
    echo "POSTGRES_USER=postgres"
    for name in POSTGRES_PASSWORD DB_PASSWORD_APP_ADMIN DB_PASSWORD_SVC_IDENTITY DB_PASSWORD_SVC_TRANSIT \
      DB_PASSWORD_SVC_ACCESSIBILITY DB_PASSWORD_SVC_PLACES DB_PASSWORD_REPORTING RABBITMQ_PASSWORD SEED_DEMO_PASSWORD; do
      echo "$name=$(openssl rand -hex 16)"
    done
    echo "RABBITMQ_USER=heatmap"
    echo "JWT_PRIVATE_KEY=$key"
    echo "JWT_KEY_ID=e2e"
    echo "WEB_PORT=${E2E_WEB_PORT:-8088}"
    echo "E2E_WEB_PORT=${E2E_WEB_PORT:-8088}"
    # The per-route limits stay as in the contracts, counted per 10 s instead of per minute,
    # so repeated test runs from one address do not hit them.
    echo "RATE_LIMIT_WINDOW_S=10"
  } > "$env_file"
  chmod 600 "$env_file"
}

compose() {
  docker compose -p heatmap-e2e --env-file "$env_file" \
    -f "$root/infra/compose/docker-compose.yml" -f "$root/infra/compose/e2e.yml" --profile full "$@"
}

case "${1:-}" in
  up)
    [ -f "$env_file" ] || generate_env
    compose up -d --build --wait --wait-timeout 600
    echo "end-to-end stack ready at http://localhost:${E2E_WEB_PORT:-8088}"
    ;;
  down)
    [ -f "$env_file" ] || generate_env
    compose down -v --remove-orphans
    ;;
  logs)
    compose logs --no-color --timestamps
    ;;
  *)
    echo "usage: scripts/e2e.sh up|down|logs" >&2
    exit 2
    ;;
esac
