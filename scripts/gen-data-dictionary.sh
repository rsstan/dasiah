#!/usr/bin/env bash
# Regenerates docs/db/data-dictionary.md from the live database catalog.
# Run after every migration (CI fails if the committed file differs).
# Uses the standard PG* environment variables; connect as app_admin.
set -euo pipefail
out="${1:-docs/db/data-dictionary.md}"
q() { psql -X -At -v ON_ERROR_STOP=1 -c "$1"; }
schemas="identity transit transit_staging accessibility places"

{
echo "# Data dictionary"
echo
echo "Generated by \`scripts/gen-data-dictionary.sh\` from the database catalog. Do not edit by hand:"
echo "change the migration (including \`COMMENT ON\`) and regenerate."
echo
echo "Key column: PK = primary key, FK = foreign key, UQ = unique. Personal data is marked PII in the description."
for s in $schemas; do
  echo; echo "## Schema \`$s\`"; echo
  q "SELECT coalesce(obj_description('$s'::regnamespace), '')"
  if [ "$s" != transit_staging ]; then
    echo; echo '```mermaid'; echo 'erDiagram'
    # Entities with attributes: type (pg_type name, domains by their own name) and key markers.
    q "SELECT format(E'  %s {\n%s\n  }', c.relname, string_agg(format('    %s %s%s', t.typname, a.attname,
              coalesce(' ' || (SELECT string_agg(DISTINCT key, ', ') FROM (
                                 SELECT CASE k.contype WHEN 'p' THEN 'PK' ELSE 'FK' END AS key
                                   FROM pg_constraint k WHERE k.conrelid = c.oid AND a.attnum = ANY (k.conkey) AND k.contype IN ('p', 'f')
                                 UNION ALL  -- unique constraints and full (non-partial) unique indexes
                                 SELECT 'UK' FROM pg_index i WHERE i.indrelid = c.oid AND i.indisunique AND NOT i.indisprimary
                                   AND i.indpred IS NULL AND a.attnum = ANY (i.indkey::int2[])) keys), '')), E'\n' ORDER BY a.attnum))
       FROM pg_class c JOIN pg_attribute a ON a.attrelid = c.oid JOIN pg_type t ON t.oid = a.atttypid
       WHERE c.relnamespace = '$s'::regnamespace AND c.relkind IN ('r','p') AND c.relname <> 'pgmigrations'
         AND a.attnum > 0 AND NOT a.attisdropped
       GROUP BY c.oid, c.relname ORDER BY c.relname"
    q "SELECT format('  %s %s--o{ %s : \"%s\"', pc.relname, '||', cc.relname, string_agg(a.attname, ',' ORDER BY k.ord))
       FROM pg_constraint c
       JOIN pg_class cc ON cc.oid = c.conrelid JOIN pg_class pc ON pc.oid = c.confrelid
       CROSS JOIN LATERAL unnest(c.conkey) WITH ORDINALITY k(attnum, ord)
       JOIN pg_attribute a ON a.attrelid = c.conrelid AND a.attnum = k.attnum
       WHERE c.contype = 'f' AND c.connamespace = '$s'::regnamespace
       GROUP BY c.oid, pc.relname, cc.relname ORDER BY pc.relname, cc.relname"
    echo '```'
  fi
  for t in $(q "SELECT relname FROM pg_class WHERE relnamespace = '$s'::regnamespace AND relkind IN ('r','p') ORDER BY relname"); do
    echo; echo "### \`$s.$t\`"; echo
    q "SELECT coalesce(obj_description('$s.$t'::regclass), '_no description_')"
    echo; echo "| Column | Type | Null | Default | Key | Description |"; echo "| --- | --- | --- | --- | --- | --- |"
    q "SELECT format('| %s | %s | %s | %s | %s | %s |', a.attname, format_type(a.atttypid, a.atttypmod),
              CASE WHEN a.attnotnull THEN 'no' ELSE 'yes' END,
              coalesce(replace(pg_get_expr(d.adbin, d.adrelid), '|', '\|'), CASE WHEN a.attidentity <> '' THEN 'identity' ELSE '' END),
              coalesce((SELECT string_agg(DISTINCT CASE c.contype WHEN 'p' THEN 'PK' WHEN 'f' THEN 'FK' WHEN 'u' THEN 'UQ' END, ', ')
                        FROM pg_constraint c WHERE c.conrelid = a.attrelid AND a.attnum = ANY (c.conkey) AND c.contype IN ('p','f','u')), ''),
              coalesce(replace(col_description(a.attrelid, a.attnum), '|', '\|'), ''))
       FROM pg_attribute a LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
       WHERE a.attrelid = '$s.$t'::regclass AND a.attnum > 0 AND NOT a.attisdropped ORDER BY a.attnum"
    c=$(q "SELECT format('- \`%s\`: %s', conname, replace(pg_get_constraintdef(oid), E'\n', ' ')) FROM pg_constraint
           WHERE conrelid = '$s.$t'::regclass AND contype IN ('c','x','f','u') ORDER BY contype, conname")
    [ -n "$c" ] && { echo; echo "Constraints:"; echo; echo "$c"; }
    i=$(q "SELECT format('- \`%s\`: %s', indexrelid::regclass, regexp_replace(pg_get_indexdef(indexrelid), '^.* USING ', ''))
           FROM pg_index WHERE indrelid = '$s.$t'::regclass AND NOT indisprimary ORDER BY 1")
    [ -n "$i" ] && { echo; echo "Indexes:"; echo; echo "$i"; }
    g=$(q "SELECT format('- \`%s\`: %s %s', tgname, CASE WHEN tgtype & 2 > 0 THEN 'BEFORE' ELSE 'AFTER' END, tgfoid::regproc)
           FROM pg_trigger WHERE tgrelid = '$s.$t'::regclass AND NOT tgisinternal ORDER BY 1")
    [ -n "$g" ] && { echo; echo "Triggers:"; echo; echo "$g"; }
  done
  v=$(q "SELECT format('| \`%s\` | %s | %s |', c.relname, CASE c.relkind WHEN 'v' THEN 'view' ELSE 'materialized view' END, coalesce(obj_description(c.oid), ''))
         FROM pg_class c WHERE c.relnamespace = '$s'::regnamespace AND c.relkind IN ('v','m') ORDER BY 1")
  [ -n "$v" ] && { echo; echo "### Views in \`$s\`"; echo; echo "| Name | Kind | Description |"; echo "| --- | --- | --- |"; echo "$v"; }
  f=$(q "SELECT format('| \`%s(%s)\` | %s | %s |', p.proname, pg_get_function_identity_arguments(p.oid),
                CASE p.prokind WHEN 'p' THEN 'procedure' ELSE CASE WHEN p.prorettype = 'trigger'::regtype THEN 'trigger function' ELSE 'function' END END,
                coalesce(obj_description(p.oid), ''))
         FROM pg_proc p WHERE p.pronamespace = '$s'::regnamespace ORDER BY 1")
  [ -n "$f" ] && { echo; echo "### Routines in \`$s\`"; echo; echo "| Name | Kind | Description |"; echo "| --- | --- | --- |"; echo "$f"; }
done
echo; echo "## Privileges"; echo
echo "| Schema | Object | Grantee | Privileges |"; echo "| --- | --- | --- | --- |"
q "SELECT format('| %s | %s | %s | %s |', table_schema, table_name, grantee, string_agg(privilege_type, ', ' ORDER BY privilege_type))
   FROM information_schema.role_table_grants
   WHERE table_schema IN ('identity','transit','transit_staging','accessibility','places') AND grantee <> 'app_admin'
   GROUP BY table_schema, table_name, grantee ORDER BY table_schema, table_name, grantee"
} > "$out"
echo "wrote $out"
